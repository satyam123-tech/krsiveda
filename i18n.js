// Applies translations to every [data-i18n] element and [data-i18n-placeholder] input.
function applyI18n(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (el.dataset.i18nEn === undefined) el.dataset.i18nEn = el.textContent;
    const hi = I18N_HI[el.getAttribute('data-i18n')];
    el.textContent = (lang === 'hi' && hi) ? hi : el.dataset.i18nEn;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    if (el.dataset.i18nPhEn === undefined) el.dataset.i18nPhEn = el.getAttribute('placeholder') || '';
    const hi = I18N_HI[el.getAttribute('data-i18n-placeholder')];
    el.setAttribute('placeholder', (lang === 'hi' && hi) ? hi : el.dataset.i18nPhEn);
  });
  document.documentElement.lang = lang === 'hi' ? 'hi' : 'en';
}
